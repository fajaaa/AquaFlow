using AquaFlow.Model;
using AquaFlow.Services.Database;
using Microsoft.EntityFrameworkCore;

namespace AquaFlow.Services;

// Why staging instead of "save the business change, then create the notification":
// Stage only ADDS the Notification and its UserNotification rows to the request's DbContext; the
// business code's own SaveChanges (TransitionToAsync of a state machine, the Serializable
// CreditInvoiceAsync transaction, ...) then writes them in the same SaveChanges/transaction as the
// status change itself. So the two can never diverge: if the status changed, the notification exists,
// and if the save fails or rolls back (concurrency, overpay guard, DB error), no notification about a
// change that never happened is left behind. A separate "after save" insert could fail on its own
// (customer never told) or run after a rolled-back change (customer told something false).
// Where the record is brand new, its id is generated by the INSERT itself, so those callers save the
// record, stage, and save again inside one explicit transaction - same atomicity, two SaveChanges.
//
// Push (FCM) is the only part that runs after the commit (DispatchPendingPushAsync): an external call
// can't be part of a DB transaction, and a push failure must never undo the business change.
public class SystemNotificationService : ISystemNotificationService
{
    private const int TitleMaxLength = 150;

    private readonly AquaFlowDbContext _dbContext;
    private readonly NotificationPushDispatcher _pushDispatcher;
    private readonly List<(Notification Notification, List<int> RecipientUserIds)> _pending = new();

    public SystemNotificationService(AquaFlowDbContext dbContext, NotificationPushDispatcher pushDispatcher)
    {
        _dbContext = dbContext;
        _pushDispatcher = pushDispatcher;
    }

    public void Stage(SystemNotificationMessage message, IEnumerable<int> recipientUserIds, int actorUserId, bool notifyActor = false)
    {
        var recipients = recipientUserIds
            .Where(userId => userId > 0 && (notifyActor || userId != actorUserId))
            .Distinct()
            .ToList();
        if (recipients.Count == 0)
        {
            return;
        }

        var now = DateTime.UtcNow;
        var notification = new Notification
        {
            Title = message.Title.Length > TitleMaxLength ? message.Title[..TitleMaxLength] : message.Title,
            Body = message.Body,
            Type = message.Type,
            Audience = NotificationAudience.Direct,
            IsSystem = true,
            RelatedEntityType = message.RelatedEntityType,
            RelatedEntityId = message.RelatedEntityId,
            CreatedById = actorUserId,
            CreatedAt = now
        };

        // Added through the navigation, so EF fills in NotificationId for the inbox rows during the
        // same SaveChanges that inserts the notification.
        foreach (var userId in recipients)
        {
            notification.UserNotifications.Add(new UserNotification { UserId = userId, CreatedAt = now });
        }

        _dbContext.Notifications.Add(notification);
        _pending.Add((notification, recipients));
    }

    public Task<List<int>> GetUserIdsWithPermissionAsync(string permissionCode)
    {
        var code = permissionCode.ToLower();

        return _dbContext.Users
            .AsNoTracking()
            .Where(user => user.IsActive && !user.IsDeleted)
            .Where(user => _dbContext.UserRolePermissions.Any(assignment =>
                assignment.UserRoleId == user.UserRoleId &&
                assignment.Permission != null &&
                assignment.Permission.IsActive &&
                assignment.Permission.Code.ToLower() == code))
            .Select(user => user.Id)
            .ToListAsync();
    }

    public Task<int?> GetCustomerUserIdAsync(int customerProfileId)
    {
        return _dbContext.CustomerProfiles
            .Where(profile => profile.Id == customerProfileId)
            .Select(profile => (int?)profile.UserId)
            .FirstOrDefaultAsync();
    }

    public Task<int?> GetCollectorUserIdAsync(int collectorProfileId)
    {
        return _dbContext.CollectorProfiles
            .Where(profile => profile.Id == collectorProfileId)
            .Select(profile => (int?)profile.UserId)
            .FirstOrDefaultAsync();
    }

    public async Task DispatchPendingPushAsync()
    {
        if (_pending.Count == 0)
        {
            return;
        }

        var staged = _pending.ToList();
        _pending.Clear();

        foreach (var (notification, recipientUserIds) in staged)
        {
            if (_dbContext.Entry(notification).State == EntityState.Added)
            {
                // Its save failed (and the caller swallowed that): never push about it, and make sure
                // a later SaveChanges in this scope can't persist it after the fact.
                DiscardUnsaved(notification);
                continue;
            }

            await _pushDispatcher.SendAsync(notification, recipientUserIds);
        }
    }

    private void DiscardUnsaved(Notification notification)
    {
        // Copy first: detaching an inbox row makes EF fix up (remove it from) this navigation.
        foreach (var userNotification in notification.UserNotifications.ToList())
        {
            _dbContext.Entry(userNotification).State = EntityState.Detached;
        }

        _dbContext.Entry(notification).State = EntityState.Detached;
    }
}
