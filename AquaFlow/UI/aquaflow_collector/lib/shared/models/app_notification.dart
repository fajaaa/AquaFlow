class AppNotification {
  const AppNotification({
    required this.id,
    required this.title,
    required this.body,
    required this.type,
    required this.audience,
    required this.createdById,
    required this.createdAt,
    required this.updatedAt,
    this.settlementId,
    this.validUntil,
    this.isSystem = false,
    this.relatedEntityType,
    this.relatedEntityId,
  });

  final int id;
  final String title;
  final String body;
  final String type;
  final String audience;
  final int? settlementId;
  final int createdById;
  final DateTime? validUntil;
  final DateTime? createdAt;
  final DateTime? updatedAt;

  /// True for a notification generated by a business event on the backend
  /// (`SystemNotificationService`), false for an admin-authored announcement.
  final bool isSystem;

  /// The record a system notification is about - a backend
  /// `RelatedEntityTypes` value (`Invoice`, `FaultReport`,
  /// `WaterMeterRequest`, `SupportTicket`) plus its id - i.e. the deep-link
  /// target behind the "Otvori" button (see `NotificationDeepLinks`). Both
  /// null for admin notifications, and for a backend that predates them.
  final String? relatedEntityType;
  final int? relatedEntityId;

  factory AppNotification.fromJson(Map<String, dynamic> json) {
    return AppNotification(
      id: (json['id'] as num?)?.toInt() ?? 0,
      title: (json['title'] ?? '') as String,
      body: (json['body'] ?? '') as String,
      type: (json['type'] ?? '') as String,
      audience: (json['audience'] ?? '') as String,
      settlementId: (json['settlementId'] as num?)?.toInt(),
      createdById: (json['createdById'] as num?)?.toInt() ?? 0,
      validUntil: _date(json['validUntil']),
      createdAt: _date(json['createdAt']),
      updatedAt: _date(json['updatedAt']),
      isSystem: json['isSystem'] == true,
      relatedEntityType: _nonEmpty(json['relatedEntityType']),
      relatedEntityId: (json['relatedEntityId'] as num?)?.toInt(),
    );
  }

  static DateTime? _date(Object? value) {
    if (value is! String || value.isEmpty) return null;
    return DateTime.tryParse(value)?.toLocal();
  }

  static String? _nonEmpty(Object? value) {
    if (value is! String) return null;
    final trimmed = value.trim();
    return trimmed.isEmpty ? null : trimmed;
  }
}
